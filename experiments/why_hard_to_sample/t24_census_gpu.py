import numpy as np

import t23_t24_common as C
from t23_t24_common import ARMS


def _now():
    return datetime.now(timezone.utc).isoformat()


def build_jax_ops(prob_model, hvp_chunk):
    import jax
    import jax.numpy as jnp

    def f(z):
        return prob_model.log_prob(z[None])[0][0]

    gradf = jax.grad(f)

    def _hvp_one(z, v):
        return jax.jvp(gradf, (z,), (v,))[1]

    hvp_batch = jax.jit(jax.vmap(_hvp_one))
    hess = jax.jit(jax.hessian(f))
    f_batch = jax.jit(jax.vmap(f))

    def f_np(Z):
        Z = np.asarray(Z, np.float64)
        out = np.empty(Z.shape[0], np.float64)
        for s in range(0, Z.shape[0], 16):
            e = min(s + 16, Z.shape[0])
            out[s:e] = np.asarray(f_batch(jnp.asarray(Z[s:e]))).reshape(-1)
        return out

    def hvp_chunked(Z, V, tag=""):
        Z = np.asarray(Z, np.float64); V = np.asarray(V, np.float64)
        n = Z.shape[0]; out = np.empty_like(Z)
        t0 = time.perf_counter(); nch = (n + hvp_chunk - 1) // hvp_chunk
        for ci, s in enumerate(range(0, n, hvp_chunk)):
            e = min(s + hvp_chunk, n)
            out[s:e] = np.asarray(hvp_batch(jnp.asarray(Z[s:e]), jnp.asarray(V[s:e])))
            if ci % 10 == 0 or e == n:
                print(f"    [hvp {tag}] chunk {ci+1}/{nch} rows {e}/{n} "
                      f"({time.perf_counter()-t0:.1f}s)", flush=True)
        return out

    def dense_hessian(z):
        return np.asarray(hess(jnp.asarray(np.asarray(z, np.float64))), np.float64)

    return f_np, hvp_chunked, dense_hessian


def census_ct(pos, steps, Sig_inv, numer_fn, tag):
    """c_t at every (chain, step) for the census segment.
    pos (C,4000,14); steps: 1-D global step indices.
    numer_fn(Zt,Dz,tag)->Dz'(-H)Dz. Returns dict of (C,S) arrays."""
    Cn = pos.shape[0]; S = len(steps)
    Zt = np.empty((Cn * S, pos.shape[2])); Dz = np.empty_like(Zt)
    for c in range(Cn):
        for j, t in enumerate(steps):
            Zt[c * S + j] = pos[c, t]
            Dz[c * S + j] = pos[c, t] - pos[c, t - 1]
    num = numer_fn(Zt, Dz, tag)
    denom_pre = np.einsum("ij,ij->i", Dz @ Sig_inv, Dz)
    denom_euc = np.einsum("ij,ij->i", Dz, Dz)
    with np.errstate(divide="ignore", invalid="ignore"):
        c_t = (num / denom_pre).reshape(Cn, S)
        c_t_eucl = (num / denom_euc).reshape(Cn, S)
    return {"c_t": c_t, "c_t_eucl": c_t_eucl,
            "num": num.reshape(Cn, S), "Zt": Zt.reshape(Cn, S, -1)}


def run_arm(arm, hvp_chunk, limit):
    from common import load_target

    print(f"\n========== T24 arm={arm} ==========", flush=True)
    prob_model, qz, z_center, dim, param_names = load_target(ARMS[arm]["system_dir"])
    bnd = C.derive_bounded(param_names, arm)
    f_np, hvp_chunked, dense_hessian = build_jax_ops(prob_model, hvp_chunk)

    # reference eigenbasis of -H(z_ref) (for power-iteration init = eigvec 1)
    chain0, tstep0 = ARMS[arm]["z_init_ct"]
    z_ref = np.asarray(np.load(ARMS[arm]["ref_samples"])["samples_z"][chain0, tstep0], np.float64)
    H_ref = dense_hessian(z_ref)
    negH = -0.5 * (H_ref + H_ref.T)
    ev, evec = np.linalg.eigh(negH)
    order = np.argsort(ev)[::-1]
    ref_eigvals = ev[order]; ref_eigvecs = evec[:, order]
    v1_init = ref_eigvecs[:, 0]
    print(f"[t24:{arm}] z_ref logp={float(f_np(z_ref[None])[0]):.4f}; "
          f"eig(-H) top={ref_eigvals[0]:.4g}", flush=True)

    seg_len = int(limit) if limit else C.CENSUS_LEN
    steps = np.arange(C.CENSUS_START, C.CENSUS_START + seg_len)
    if steps[-1] >= C.RESULTS_HI:
        raise ValueError(f"census segment {steps[0]}..{steps[-1]} exceeds results "
                         f"phase end {C.RESULTS_HI}")
    print(f"[t24:{arm}] census segment global steps {steps[0]}..{steps[-1]} "
          f"({seg_len} steps x 8 chains)", flush=True)

    # ---- REAL seed 1 census ------------------------------------------------
    run = C.load_run(C.seed_npz(arm, C.CLONE_SEED))   # seed 1
    Sigma, dmax = C.frozen_sigma(run, arm, 1)
    Sig_inv = C.sigma_inv(Sigma)
    xi_seg = run["xi"][:, steps]                        # (8,S)
    eps_seg = run["step_size"][:, steps]

    def real_numer(Zt, Dz, tag):
        Hv = hvp_chunked(Zt, Dz, tag)
        return -np.einsum("ij,ij->i", Dz, Hv)

    cen = census_ct(run["position"], steps, Sig_inv, real_numer, f"{arm}:census")
    c_t = cen["c_t"]
    print(f"[t24:{arm}] REAL census c_t: median={np.nanmedian(c_t):.4g} "
          f"max={np.nanmax(c_t):.4g}", flush=True)

    # ---- power iteration at top-12 spikes + 12 matched calm ----------------
    Cn, S = c_t.shape
    flat = c_t.reshape(-1)
    n_top = min(C.CENSUS_N_TOP, np.sum(np.isfinite(flat)))
    top_flat = np.argsort(np.where(np.isfinite(flat), flat, -np.inf))[::-1][:n_top]
    spike_ct = np.array([int(i // S) for i in top_flat])
    spike_st = np.array([int(steps[i % S]) for i in top_flat])
    # matched same-segment (=same chain) median-c calm points
    calm_ct, calm_st = [], []
    for c in spike_ct:
        med = np.nanmedian(c_t[c])
        j = int(np.nanargmin(np.abs(c_t[c] - med)))
        calm_ct.append(int(c)); calm_st.append(int(steps[j]))
    calm_ct = np.array(calm_ct); calm_st = np.array(calm_st)

    pi_ct = np.concatenate([spike_ct, calm_ct])
    pi_st = np.concatenate([spike_st, calm_st])
    Zpi = np.array([run["position"][c, t] for c, t in zip(pi_ct, pi_st)])
    lam1, v1 = power_iterate_negH(hvp_chunked, Zpi, v1_init, arm)
    v1_loadings = v1 @ ref_eigvecs                     # loadings on ref eigenbasis
    m = len(spike_ct)
    print(f"[t24:{arm}] power-iter lambda1 spike median={np.median(lam1[:m]):.4g} "
          f"calm median={np.median(lam1[m:]):.4g}", flush=True)

    # ---- CLONE seed 1 census (analytic; no power iteration) ----------------
    clone_run = C.load_run(C.clone_run_npz(arm))
    Sig_c, dmax_c = C.frozen_sigma(clone_run, arm, "clone")
    Sig_inv_c = C.sigma_inv(Sig_c)
    P_clone, _L = C.clone_precision(arm)
    xi_seg_c = clone_run["xi"][:, steps]

    def clone_numer(Zt, Dz, tag):
        return C.quad(P_clone, Dz)

    cen_c = census_ct(clone_run["position"], steps, Sig_inv_c, clone_numer, f"{arm}:clone")
    print(f"[t24:{arm}] CLONE census c_t: median={np.nanmedian(cen_c['c_t']):.4g} "
          f"max={np.nanmax(cen_c['c_t']):.4g}", flush=True)

    # ---- save --------------------------------------------------------------
    os.makedirs(C.T24_OUT, exist_ok=True)
    suffix = "_smoke" if limit else ""
    npz = {
        "steps": steps.astype(np.int64),
        "real_c_t": c_t, "real_c_t_eucl": cen["c_t_eucl"], "real_xi": xi_seg,
        "real_eps": eps_seg,
        "clone_c_t": cen_c["c_t"], "clone_c_t_eucl": cen_c["c_t_eucl"], "clone_xi": xi_seg_c,
        "pi_spike_chain": spike_ct, "pi_spike_step": spike_st,
        "pi_calm_chain": calm_ct, "pi_calm_step": calm_st,
        "pi_lambda1": lam1, "pi_v1": v1, "pi_v1_loadings": v1_loadings,
        "pi_n_spike": np.int64(m),
        "ref_eigvals": ref_eigvals, "ref_eigvecs": ref_eigvecs, "z_ref": z_ref,
        "param_names": np.array(list(param_names)),
        "bounded_idx": np.array(bnd["bounded_idx"], dtype=np.int64),
    }
    npz_path = os.path.join(C.T24_OUT, f"t24_{arm}{suffix}.npz")
    np.savez(npz_path, **npz)
    print(f"[t24:{arm}] wrote {npz_path}", flush=True)

    manifest = {
        "experiment": "T24 encounter-geometry census (carousel)",
        "arm": arm, "status": "proposed (UNCERTIFIED)", "timestamp_utc": _now(),
        "smoke_limit": (int(limit) if limit else None), "hvp_chunk": int(hvp_chunk),
        "xi_alignment": C.XI_ALIGNMENT, "metric_note": C.METRIC_NOTE,
        "census": {"start": int(steps[0]), "end": int(steps[-1]),
                   "seg_len": int(seg_len), "n_chains": int(Cn),
                   "spike_factor": C.CENSUS_SPIKE_FACTOR},
        "power_iter": {"iters": C.POWER_ITERS, "init": "ref_eigvec_1",
                       "n_spike": int(m), "n_calm": int(len(calm_ct))},
        "param_names": list(param_names),
        "bounded": {"idx": bnd["bounded_idx"], "names": bnd["bounded_names"],
                    "rs_index": bnd["rs_index"], "alpha_rs_index": bnd["alpha_rs_index"]},
        "sigma_frozen_maxdiff": {"real_seed1": dmax, "clone": dmax_c},
        "ref_eig_top": float(ref_eigvals[0]),
    }
    man_path = os.path.join(C.T24_OUT, f"t24_{arm}{suffix}.manifest.json")
    with open(man_path, "w") as fh:
        json.dump(manifest, fh, indent=2)
    print(f"[t24:{arm}] wrote {man_path}", flush=True)
    n_hvp = Cn * seg_len + C.POWER_ITERS * len(pi_ct) + dim
    return n_hvp


def power_iterate_negH(hvp_chunked, Z, v_init, arm):
    """Power iteration for the top eigenpair of -H at each row point of Z (m,14).
    Deterministic init v_init (shared). POWER_ITERS fixed iterations. Returns
    (lambda1 (m,), v1 (m,14)) with lambda1 = v'(-H)v (Rayleigh) at the final v."""
    m, d = Z.shape
    V = np.broadcast_to(v_init / np.linalg.norm(v_init), (m, d)).copy()
    for it in range(C.POWER_ITERS):
        Hv = hvp_chunked(Z, V, f"{arm}:power[{it+1}/{C.POWER_ITERS}]")
        negHv = -Hv
        nrm = np.linalg.norm(negHv, axis=1, keepdims=True)
        nrm = np.where(nrm > 0, nrm, 1.0)
        V = negHv / nrm
    Hv = hvp_chunked(Z, V, f"{arm}:power[rayleigh]")
    lam1 = -np.einsum("ij,ij->i", V, Hv)               # v'(-H)v
    return lam1, V


def main(argv=None):
    ap = argparse.ArgumentParser(description="T24 encounter-geometry census (GPU)")
    ap.add_argument("--arm", choices=["old", "new", "both"], default="both")
    ap.add_argument("--hvp-chunk", type=int, default=C.HVP_CHUNK_DEFAULT)
    ap.add_argument("--limit", type=int, default=0,
                    help="smoke: steps per segment (default full 256); writes *_smoke.npz")
    args = ap.parse_args(argv)

    from common import assert_x64
    assert_x64()
    print(f"[t24] float64 asserted; WHTS_CONV_PRECISION="
          f"{os.environ.get('WHTS_CONV_PRECISION')}; hvp_chunk={args.hvp_chunk} "
          f"limit={args.limit or 'none'}", flush=True)

    arms = ["old", "new"] if args.arm == "both" else [args.arm]
    t0 = time.perf_counter()
    total = 0
    for arm in arms:
        total += run_arm(arm, args.hvp_chunk, args.limit)
    print(f"\n[t24] DONE arms={arms} total_HVPs~{total} "
          f"wall={time.perf_counter()-t0:.1f}s (PROPOSED / UNCERTIFIED)", flush=True)


if __name__ == "__main__":
    main()
