"""T24 -- encounter-geometry census (GPU stage).

Pre-registered 2026-07-03 (docs/logs/why-hard-to-sample.md). Cause hypothesis:
the stationary xi tail is generated by LOCALIZED curvature encounters along the
actual chain path (spikes with rate/width/spacing structure), not a diffuse
background elevation.

Design (deviation from T10 justified in the registration: T19 already nulled
lambda1(GN) at xi-stratified draws, so the census scalar is c_t at EVERY step):
  * seed-1 only, both arms + both clones;
  * 8 chains x one contiguous 256-step results-phase segment (fixed offset,
    global steps CENSUS_START..CENSUS_START+CENSUS_LEN-1 = 2500..2755 -- chosen
    500 steps into the results phase, clear of the burnin->results transient,
    SAME for every chain/arm);
  * c_t at every step (real: 1 HVP/step; clones: analytic -H = clone precision);
  * lambda1(-H) power iteration (POWER_ITERS=12, deterministic init = reference
    eigenvector 1 of -H(z_ref)) ONLY at the top-12 pooled census spikes + 12
    matched same-segment median-c calm points, REAL arms only (v1 loadings for
    direction identity; cross-check vs T23-C3).

c_t and the xi<->displacement alignment follow t23_t24_common.py (traced from
source). Per-segment / pooled statistics and F-T24 adjudication live in the
login-node t23_t24_analyze.py; this stage only PRODUCES UNCERTIFIED arrays.

Outputs (HARDCODED dir): results_carousel/phaseC/t24/t24_{arm}.npz + manifest.
--limit N -> fewer steps per segment (smoke); writes t24_{arm}_smoke.npz.
"""
from __future__ import annotations

